import type { Agent, Property, PropertyFeatureFlags, PropertyImage } from '@/domain/property';
import { AGENTS } from './agents.mock';

const agentById = (id: string): Agent => {
  const agent = AGENTS.find((a) => a.id === id);
  if (!agent) throw new Error(`Unknown agent ${id}`);
  return agent;
};

const features = (overrides: Partial<PropertyFeatureFlags> = {}): PropertyFeatureFlags => ({
  parking: false,
  elevator: false,
  balcony: false,
  furnished: false,
  petFriendly: false,
  newConstruction: false,
  registered: true,
  ...overrides,
});

const IMG_W = 1200;
const IMG_H = 900;

const images = (slug: string, scenes: string[], title: string): PropertyImage[] =>
  scenes.map((scene, index) => ({
    id: `${slug}-img-${index + 1}`,
    url: `https://picsum.photos/seed/${slug}-${index + 1}/${IMG_W}/${IMG_H}`,
    alt: `${title} — ${scene}`,
    width: IMG_W,
    height: IMG_H,
    isCover: index === 0,
    order: index,
  }));

type PropertySeed = Omit<Property, 'images'> & { scenes: string[] };

const seed = (p: PropertySeed): Property => {
  const { scenes, ...rest } = p;
  return { ...rest, images: images(p.slug, scenes, p.title) };
};

